//! Modules shared by the golden, determinism and compiler tests.
//!
//! Each golden file under `tests/golden/` is the printed form of one module
//! built here, so the compiler test and the golden test check the same output.

#![allow(dead_code)]

use std::path::PathBuf;

use wesley_typescript_syntax::{Declaration, Module, Property, TsType};

/// One golden case: the module and the file its printed form is pinned to.
pub struct Case {
    pub file: &'static str,
    pub module: Module,
}

pub fn golden_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("golden")
}

pub fn cases() -> Vec<Case> {
    vec![
        Case {
            file: "every_variant.ts",
            module: every_variant(),
        },
        Case {
            file: "messages.ts",
            module: messages(),
        },
    ]
}

fn prop(name: &str, ty: TsType) -> Property {
    Property {
        name: name.to_owned(),
        optional: false,
        readonly: false,
        ty,
        doc: None,
    }
}

/// An interface that uses every `TsType` variant, optional and readonly
/// properties, a key that is not an identifier, and JSDoc on the module,
/// the declarations and the properties.
pub fn every_variant() -> Module {
    let mut id = prop("id", TsType::String);
    id.readonly = true;
    id.doc = Some("The run's identity.".to_owned());

    let mut note = prop("note", TsType::Unknown);
    note.optional = true;
    note.doc = Some("A note.\n\nIt spans lines and says */ safely.".to_owned());

    let mut what_ran = prop("what-ran", TsType::Ref("Command".to_owned()));
    what_ran.readonly = true;
    what_ran.optional = true;
    what_ran.doc = Some("The command, under a key that is not an identifier.".to_owned());

    let mut nested_exit = prop("exit", TsType::Number);
    nested_exit.doc = Some("The exit code.".to_owned());

    let run = Declaration::Interface {
        name: "Run".to_owned(),
        doc: Some("One run of a program.".to_owned()),
        properties: vec![
            id,
            prop("count", TsType::Number),
            prop("ok", TsType::Boolean),
            note,
            prop("parent", TsType::Null),
            prop(
                "quoted",
                TsType::StringLiteral("say \"hi\" \\ to\nthe tab\tand é".to_owned()),
            ),
            prop("answer", TsType::NumberLiteral(42)),
            prop("below", TsType::NumberLiteral(-7)),
            prop("always", TsType::BooleanLiteral(true)),
            prop("never", TsType::BooleanLiteral(false)),
            what_ran,
            prop("tags", TsType::Array(Box::new(TsType::String))),
            prop(
                "mixed",
                TsType::Array(Box::new(TsType::Union(vec![
                    TsType::String,
                    TsType::Number,
                ]))),
            ),
            prop(
                "grid",
                TsType::Array(Box::new(TsType::Array(Box::new(TsType::Number)))),
            ),
            prop(
                "maybe",
                TsType::Union(vec![TsType::Ref("Command".to_owned()), TsType::Null]),
            ),
            prop(
                "outcome",
                TsType::Object(vec![
                    nested_exit,
                    prop("signal", TsType::Union(vec![TsType::String, TsType::Null])),
                ]),
            ),
            prop("env", TsType::Record(Box::new(TsType::String))),
            prop(
                "counts",
                TsType::Record(Box::new(TsType::Union(vec![TsType::Number, TsType::Null]))),
            ),
            prop("empty", TsType::Object(Vec::new())),
        ],
    };

    let command = Declaration::TypeAlias {
        name: "Command".to_owned(),
        doc: None,
        ty: TsType::Object(vec![
            prop("argv", TsType::Array(Box::new(TsType::String))),
            prop("cwd", TsType::String),
        ]),
    };

    let outcome = Declaration::TypeAlias {
        name: "Outcome".to_owned(),
        doc: Some("How a run ended.".to_owned()),
        ty: TsType::Union(vec![
            TsType::StringLiteral("passed".to_owned()),
            TsType::StringLiteral("failed".to_owned()),
            TsType::StringLiteral("what-ran".to_owned()),
        ]),
    };

    Module {
        doc: Some("Generated by wesley-typescript-syntax.\nDo not edit.".to_owned()),
        declarations: vec![run, command, outcome],
    }
}

/// A discriminated union on a string-literal `event` field, the shape the
/// compiler fixtures narrow on.
pub fn messages() -> Module {
    let mut started_at = prop("at", TsType::String);
    started_at.doc = Some("When the run started.".to_owned());

    let started = Declaration::Interface {
        name: "Started".to_owned(),
        doc: Some("A run started.".to_owned()),
        properties: vec![
            prop("event", TsType::StringLiteral("started".to_owned())),
            started_at,
        ],
    };
    let finished = Declaration::Interface {
        name: "Finished".to_owned(),
        doc: Some("A run finished.".to_owned()),
        properties: vec![
            prop("event", TsType::StringLiteral("finished".to_owned())),
            prop("code", TsType::Number),
        ],
    };
    let event = Declaration::TypeAlias {
        name: "EventName".to_owned(),
        doc: Some("Every event name.".to_owned()),
        ty: TsType::Union(vec![
            TsType::StringLiteral("started".to_owned()),
            TsType::StringLiteral("finished".to_owned()),
        ]),
    };
    let message = Declaration::TypeAlias {
        name: "Message".to_owned(),
        doc: Some("Any message, told apart by `event`.".to_owned()),
        ty: TsType::Union(vec![
            TsType::Ref("Started".to_owned()),
            TsType::Ref("Finished".to_owned()),
        ]),
    };

    Module {
        doc: None,
        declarations: vec![started, finished, event, message],
    }
}
